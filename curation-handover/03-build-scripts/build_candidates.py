# Legitimately-distinct same-title films (remakes/coincidence) to keep despite norm collision
KEEP={("dune",2021),("batman",2022),("killer",1989),("hero",2002)}

def to_waves(rows,bucket):
    kept=[r for r in rows if norm(r[0]) not in existing or (norm(r[0]),r[2]) in KEEP]
    dropped=[r[0] for r in rows if norm(r[0]) in existing and (norm(r[0]),r[2]) not in KEEP]
    n=len(kept); w1=math.ceil(n/3); w2=math.ceil((n-w1)/2)
    out=[]
    for i,r in enumerate(kept):
        w=1 if i<w1 else (2 if i<w1+w2 else 3)
        out.append((w,bucket)+r)
    return out,dropped,n

