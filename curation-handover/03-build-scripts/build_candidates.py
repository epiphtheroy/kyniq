def norm(t):
    t = unicodedata.normalize("NFKD", t).encode("ascii","ignore").decode("ascii").lower()
    t = re.sub(r"\b(the|a|an)\b"," ",t)
    t = re.sub(r"[^a-z0-9]+"," ",t)
    return t.strip()

