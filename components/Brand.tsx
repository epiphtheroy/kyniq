type Art = { viewBox: string; ratio: number; paths: { fill: string; d: string }[] };

function Mark({
  art,
  height,
  className,
  label,
}: {
  art: Art;
  height: number;
  className?: string;
  label?: string;
}) {
  const width = Math.round(height * art.ratio * 100) / 100;
  return (
    <svg
      viewBox={art.viewBox}
      width={width}
      height={height}
      className={className}
      role={label ? "img" : undefined}
      aria-label={label}
      aria-hidden={label ? undefined : true}
      focusable="false"
      style={{ display: "block" }}
    >
      {art.paths.map((p, i) => (
        <path key={i} fill={p.fill} d={p.d} />
      ))}
    </svg>
  );
}

export function BrandSymbol({
  height = 24,
  label = "Metatake",
  className,
}: {
  height?: number;
  label?: string;
  className?: string;
}) {
  return <Mark art={SYMBOL} height={height} label={label} className={className} />;
}

export function BrandWordtext({ height = 14, className }: { height?: number; className?: string }) {
  return <Mark art={WORDTEXT} height={height} className={className} />;
}

export function BrandStack({
  height = 56,
  label = "Metatake",
  className,
}: {
  height?: number;
  label?: string;
  className?: string;
}) {
  return <Mark art={STACK} height={height} label={label} className={className} />;
}

/**
 * Symbol + wordtext. `size` is the symbol height; the text sits at 0.65 of it
 * (cap height ≈ 0.62 of the mark) and the gap is 0.3em of that text, both
 * driven by --brand-size so a media query can shrink the whole lockup at once
 * (see .brand-lockup in globals.css). The parent link carries the accessible name.
 */
export function BrandLockup({ size = 22, className }: { size?: number; className?: string }) {
  const style = { "--brand-size": `${size}px` } as CSSProperties;
  return (
    <span className={className ? `brand-lockup ${className}` : "brand-lockup"} style={style} aria-hidden="true">
      <Mark art={SYMBOL} height={size} className="brand-lockup__symbol" />
      <Mark art={WORDTEXT} height={Math.round(size * 0.65 * 100) / 100} className="brand-lockup__text" />
    </span>
  );
}
